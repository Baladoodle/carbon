import { expect, test, type Page } from '@playwright/test';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { launchCarbon, type CarbonApp } from './harness';

/**
 * The key table in docs/GUIDE.md is generated from the action registry: every
 * view, overlay and prompt is opened on the sample world, and every keyed
 * action registered along the way is collected. The test fails when the guide
 * and the registry disagree; `npm run guide:keys` (UPDATE_GUIDE=1) rewrites
 * the table between its markers instead.
 */

type Row = { id: string; label: string; group: string; keys: string[]; hidden: boolean };

const GUIDE = path.join(fileURLToPath(new URL('..', import.meta.url)), 'docs/GUIDE.md');
const START = '<!-- keys:start (generated by `npm run guide:keys` from the action registry) -->';
const END = '<!-- keys:end -->';

/** Sections in the order the guide lists them; an action's section is its group, or its id's prefix. */
const SECTIONS: [string, (r: Row) => boolean][] = [
  [
    'Anywhere',
    (r) =>
      (['Views', 'Window', 'AI', 'Edit'].includes(r.group) && r.id !== 'ai-log.close') ||
      r.id === 'overlay.close',
  ],
  ['Column', (r) => r.id.startsWith('column.')],
  ['Bench', (r) => r.id.startsWith('bench.')],
  ['Climate', (r) => r.id.startsWith('climate.')],
  ['Codex', (r) => r.id.startsWith('codex.') && !/^codex\.(state|kill)\./.test(r.id)],
  ['Codex: the state dialog (`s`)', (r) => r.id.startsWith('codex.state.')],
  [
    'Kill reasons (the defaults; after `x` in a spread, `g` in the state dialog)',
    (r) => r.id.startsWith('codex.kill.'),
  ],
  ['Images (in every view)', (r) => r.id.startsWith('images.')],
  ['Numbers', (r) => r.id.startsWith('numbers.')],
  ['Spread', (r) => r.id.startsWith('spread.')],
  ['Taste', (r) => r.id.startsWith('taste.')],
  ['Export', (r) => r.id.startsWith('export.')],
  ['AI log', (r) => r.id.startsWith('ai-log.')],
];
/**
 * Image actions name what they act on in the palette ("Generate concept:
 * Glide"); the guide describes the target instead.
 */
const GUIDE_LABEL: Record<string, string> = {
  'images.concept': 'Generate concept: the entity in focus, or a batch over a multi-selection',
  'images.icon': 'Generate icon: the entity in focus, or a batch over a multi-selection',
  'codex.images.concept':
    'Generate concept: the cursor row, or a batch over the selected rows shown',
  'codex.images.icon': 'Generate icon: the cursor row, or a batch over the selected rows shown',
};
/** Not listed: each repeats `ctrl+z` (it drops a nudge still waiting to be sent, then undoes as usual). */
const LEFT_OUT = new Set(['column.undo-nudge', 'climate.undo-nudge']);

const ARROWS: Record<string, string> = {
  arrowup: '↑',
  arrowdown: '↓',
  arrowleft: '←',
  arrowright: '→',
};
const keyText = (k: string): string =>
  `\`${k
    .split('+')
    .map((p) => ARROWS[p] ?? p)
    .join('+')
    .replace(/^\+$/, '+')}\``;

/** The generated block: one table per section. */
export function renderKeys(rows: Row[]): string {
  const out: string[] = [START];
  const used = new Set<string>();
  for (const [name, has] of SECTIONS) {
    const mine = rows.filter((r) => !used.has(r.id) && !LEFT_OUT.has(r.id) && has(r));
    if (mine.length === 0) continue;
    for (const r of mine) used.add(r.id);
    out.push('', `#### ${name}`, '', '| Key | Action |', '|---|---|');
    for (const r of mine)
      out.push(
        `| ${r.keys.map(keyText).join(' or ')} | ${(GUIDE_LABEL[r.id] ?? r.label).replace(/\|/g, '\\|')} |`,
      );
  }
  const orphans = rows.filter((r) => !used.has(r.id) && !LEFT_OUT.has(r.id));
  if (orphans.length > 0) throw new Error(`No section for ${orphans.map((r) => r.id).join(', ')}`);
  out.push('', END);
  return out.join('\n');
}

let carbon: CarbonApp;
test.beforeAll(async () => {
  carbon = await launchCarbon();
});
test.afterAll(async () => {
  await carbon.close();
});

const rowsNow = (page: Page): Promise<Row[]> =>
  page.evaluate(() => (window as unknown as { carbonKeyRows: () => Row[] }).carbonKeyRows());

test('@smoke the guide’s key table is the action registry', async () => {
  test.setTimeout(90_000);
  const { page } = carbon;
  const body = page.locator('body');
  const all = new Map<string, Row>();
  const take = async (): Promise<void> => {
    for (const r of await rowsNow(page)) if (!all.has(r.id)) all.set(r.id, r);
  };
  // Every view, with an entity on the Bench.
  await body.press('Control+k');
  await page.keyboard.type('Glide');
  await page.keyboard.press('Enter');
  await expect(page.getByTestId('bench-entity')).toHaveAttribute('data-entity', 'glide');
  for (const k of ['1', '2', '3', '4', '5', '6', '7']) {
    await body.press(k);
    await expect(page.locator('[data-testid^="view-"]').first()).toBeVisible();
    await take();
  }
  // The AI log.
  await body.press('Control+l');
  await expect(page.getByTestId('ai-log')).toBeVisible();
  await take();
  await page.keyboard.press('Escape');
  // Three suggestions on a Bench field: 1, 2 and 3 pick.
  await body.press('1');
  const identity = page.locator('[data-testid="bench-entity"] [data-bench-field="identity"] input');
  await identity.focus();
  await page.keyboard.press('Shift+Tab');
  await expect(page.getByTestId('three-identity')).toBeVisible();
  await take();
  await page.keyboard.press('Escape');
  await page.evaluate(() => (document.activeElement as HTMLElement | null)?.blur());
  // A spread with candidates, and its kill prompt (the reasons are keys).
  await body.press('Space');
  await expect(page.getByTestId('view-spread')).toBeVisible();
  await body.press('Enter');
  await expect(page.locator('[data-testid="spread-card"]').first()).toBeVisible();
  await expect(page.getByTestId('spread-progress')).toHaveCount(0);
  await take();
  await body.press('x');
  await expect(page.getByTestId('spread-kill-reasons')).toBeVisible();
  await take();
  await page.keyboard.press('Escape');
  // The Codex's state dialog.
  await body.press('3');
  await body.press('j');
  await body.press('s');
  await expect(page.getByTestId('codex-state-dialog')).toBeVisible();
  await take();
  await page.keyboard.press('g');
  await take();
  await page.keyboard.press('Escape');
  await expect(page.getByTestId('codex-state-dialog')).toHaveCount(0);

  const table = renderKeys([...all.values()]);
  const guide = readFileSync(GUIDE, 'utf8');
  const a = guide.indexOf(START);
  const b = guide.indexOf(END);
  expect(a, 'docs/GUIDE.md has the keys:start marker').toBeGreaterThanOrEqual(0);
  expect(b, 'docs/GUIDE.md has the keys:end marker').toBeGreaterThan(a);
  const current = guide.slice(a, b + END.length);
  if (process.env.UPDATE_GUIDE === '1') {
    writeFileSync(GUIDE, guide.slice(0, a) + table + guide.slice(b + END.length));
    return;
  }
  expect(current, 'the key table is out of date: run `npm run guide:keys`').toBe(table);
});
